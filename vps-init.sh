#!/usr/bin/env bash
# Provider-neutral, one-line VPS installer.
# Interactive: curl -fsSL https://raw.githubusercontent.com/MahaKoala/VPSsetup/main/vps-init.sh | sudo bash
# Noninteractive: VPS_USER=maha SSH_ID=mahakoala NONINTERACTIVE=1 bash vps-init.sh
# Every worker is a standalone, re-runnable script; no cloud-init required.
set -Eeuo pipefail
[[ $EUID -eq 0 ]] || { echo "Run as root (e.g. curl ... | sudo bash)" >&2; exit 1; }

ENV_FILE="${ENV_FILE:-/etc/vps/bootstrap.env}"
VPS_SETUP_REF="${VPS_SETUP_REF:-main}"
BASE="https://raw.githubusercontent.com/MahaKoala/VPSsetup/$VPS_SETUP_REF"
NONINTERACTIVE="${NONINTERACTIVE:-0}"
RUN_VERIFY="${RUN_VERIFY:-0}"
RUN_HARDEN="${RUN_HARDEN:-1}"
OVERWRITE_CONFIG="${OVERWRITE_CONFIG:-0}"
export DEBIAN_FRONTEND=noninteractive

mkdir -p /etc/vps /usr/local/sbin
umask 077
echo "=== VPSsetup: $VPS_SETUP_REF ==="

download() {
    local remote="$1" local_file="$2"
    curl -fLsS --retry 3 --connect-timeout 10 --max-time 120 \
        "$BASE/$remote" -o "$local_file"
    [[ -s "$local_file" ]] || { echo "Empty download: $remote" >&2; exit 1; }
}

new_config=0
if [[ -f "$ENV_FILE" && "$OVERWRITE_CONFIG" != "1" ]]; then
    echo "Using existing $ENV_FILE; edit this file to change settings."
    # shellcheck source=/dev/null
    source "$ENV_FILE"
else
    template="$(mktemp)"
    trap 'rm -f "$template"' EXIT
    download bootstrap.env "$template"
    # Source template defaults; variables explicitly passed by the operator win.
    # shellcheck source=/dev/null
    source "$template"
    new_config=1
fi
: "${VPS_USER:=maha}"
: "${SSH_ID:=}"
: "${SSH_GH_USER:=}"
: "${SSH_AUTHORIZED_KEYS:=}"
: "${INSTALL_BREW:=0}"
: "${INSTALL_TOOLS:=0}"
: "${INSTALL_VIBECODE_CRUSH:=0}"
: "${VPS_SETUP_REF:=main}"
: "${INSTALL_TAILSCALE:=1}"
: "${TAILSCALE_AUTHKEY:=}"

interactive=0
if [[ "$NONINTERACTIVE" != "1" && "$new_config" == "1" && -r /dev/tty && -w /dev/tty ]]; then
    interactive=1
fi

if (( interactive )); then
    echo "Press Enter to keep defaults. All actions are confirmed before execution."
    read -r -p "Linux admin username [$VPS_USER]: " answer </dev/tty
    VPS_USER="${answer:-$VPS_USER}"
    read -r -p "Hostname [auto-detect]: " answer </dev/tty
    [[ -n "$answer" ]] && VPS_HOSTNAME="$answer"
    read -r -p "SSHID identifier [$SSH_ID]: " answer </dev/tty
    SSH_ID="${answer:-$SSH_ID}"
    read -r -p "GitHub SSH-key username [$SSH_GH_USER]: " answer </dev/tty
    SSH_GH_USER="${answer:-$SSH_GH_USER}"
    read -r -p "Install Homebrew? [y/N]: " answer </dev/tty
    if [[ "$answer" =~ ^[Yy] ]]; then INSTALL_BREW=1; INSTALL_BREW_PACKAGES=1; fi
    read -r -p "Install AI coding tools? [y/N]: " answer </dev/tty
    if [[ "$answer" =~ ^[Yy] ]]; then INSTALL_TOOLS=1; INSTALL_BREW=1; INSTALL_BREW_PACKAGES=1; fi
    read -r -p "Configure optional Crush vibe-coding tools? [y/N]: " answer </dev/tty
    if [[ "$answer" =~ ^[Yy] ]]; then
        INSTALL_VIBECODE_CRUSH=1
        INSTALL_BREW=1
    fi
    read -r -p "Install Tailscale? [Y/n]: " answer </dev/tty
    [[ "$answer" =~ ^[Nn] ]] && INSTALL_TAILSCALE=0
    if [[ "$INSTALL_TAILSCALE" == "1" ]]; then
        read -r -s -p "Optional Tailscale auth key (blank to authenticate later): " answer </dev/tty
        echo
        [[ -n "$answer" ]] && TAILSCALE_AUTHKEY="$answer"
        unset answer
    fi
    read -r -p "Proceed with provisioning as $VPS_USER? [y/N]: " answer </dev/tty
    [[ "$answer" =~ ^[Yy] ]] || { echo "Cancelled"; exit 1; }
fi

if [[ "$new_config" == "1" ]]; then
    if [[ -z "$SSH_ID$SSH_GH_USER$SSH_AUTHORIZED_KEYS" ]]; then
        echo "ERROR: Configure SSH_ID, SSH_GH_USER or SSH_AUTHORIZED_KEYS before first bootstrap." >&2
        exit 1
    fi
    # Write shell-safe values, not interpolated or unescaped double-quoted secrets.
    printf '# Generated by VPSsetup; permissions 0600\n' > "$ENV_FILE"
    while IFS= read -r name; do
        [[ -n "$name" ]] || continue
        printf '%s=%q\n' "$name" "${!name}" >> "$ENV_FILE"
    done < <(awk -F= '/^[A-Z][A-Z0-9_]*=/{print $1}' "$template")
    printf 'VPS_SETUP_REF=%q\n' "$VPS_SETUP_REF" >> "$ENV_FILE"
    chmod 600 "$ENV_FILE"
fi

# Reuse the persisted settings for subsequent worker invocations.
# shellcheck source=/dev/null
source "$ENV_FILE"
VPS_SETUP_REF="${VPS_SETUP_REF:-main}"
BASE="https://raw.githubusercontent.com/MahaKoala/VPSsetup/$VPS_SETUP_REF"
if [[ "${INSTALL_VIBECODE_CRUSH:-0}" == "1" && "${INSTALL_BREW:-0}" != "1" && "${CRUSH_CONFIG_ONLY:-0}" != "1" ]]; then
    echo "ERROR: Crush needs Homebrew. Set INSTALL_BREW=1 or CRUSH_CONFIG_ONLY=1." >&2
    exit 1
fi
if [[ "${INSTALL_TOOLS:-0}" == "1" && "${INSTALL_BREW:-0}" != "1" ]]; then
    echo "ERROR: INSTALL_TOOLS=1 requires INSTALL_BREW=1." >&2
    exit 1
fi

echo "Downloading shared standalone worker scripts from $BASE"
for script in vps-swap.sh vps-bootstrap.sh vps-harden.sh vps-tools.sh VerifyChecklist.sh; do
    download "$script" "/usr/local/sbin/$script"
    chmod 700 "/usr/local/sbin/$script"
    bash -n "/usr/local/sbin/$script"
done

echo "=== Stage 1: dynamic swap ==="
/usr/local/sbin/vps-swap.sh
echo "=== Stage 2: OS packages, user, SSH keys ==="
/usr/local/sbin/vps-bootstrap.sh
if [[ "$RUN_HARDEN" == "1" ]]; then
    echo "=== Stage 3: SSH, UFW, Tailscale, security ==="
    /usr/local/sbin/vps-harden.sh
fi
if [[ "${INSTALL_TOOLS:-0}" == "1" ]]; then
    echo "=== Stage 4: optional development tools ==="
    /usr/local/sbin/vps-tools.sh
fi
if [[ "${INSTALL_VIBECODE_CRUSH:-0}" == "1" ]]; then
    echo "=== Optional stage: Crush vibe coding ==="
    download "vps-vibecode-crush.sh" "/usr/local/sbin/vps-vibecode-crush.sh"
    chmod 700 /usr/local/sbin/vps-vibecode-crush.sh
    bash -n /usr/local/sbin/vps-vibecode-crush.sh
    /usr/local/sbin/vps-vibecode-crush.sh
fi
if [[ "$RUN_VERIFY" == "1" || "$interactive" == "1" ]]; then
    echo "=== Stage 5: verification ==="
    /usr/local/sbin/VerifyChecklist.sh
fi

echo "=== VPSsetup finished; configuration: $ENV_FILE ==="
echo "Connect using: ssh $VPS_USER@<server-ip-or-hostname>"
echo "Keep an existing root console open until the new SSH key login works."
